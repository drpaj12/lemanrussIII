"""Testbench text generators (spec docs/specs/2026-10-31-htl-design.md section 4).

Netlist level: an `odin3-sim-vectors` file (src/sim/vectors_in.c; the sim pass's own format)
driving named input ports to a fixed value for a run, read back with `sim --vectors-in`.
RTL level: a self-checking iverilog testbench (`initial`/`always`, `$display`/`$finish`) --
the capability spec section 4's "testbench gap" notes Odin III's `sim` pass does not have.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Port:
    name: str
    width: int
    is_clock: bool = False


def build_vectors_file(
    inputs: list[Port], outputs: list[Port], drive: dict[str, int], cycles: int, title: str = "htl"
) -> str:
    """An odin3-sim-vectors text file driving every named `drive` input to a fixed value for
    `cycles` cycles; an undriven non-clock input bit is 0 (deterministic, not random -- this
    builds the "fires" testbench, not the "stealth" random-vector run, which uses the real `sim`
    pass's own PRNG directly instead of a crafted file).
    """
    lines = [f"# {title} seed 0 cycles {cycles}"]
    for port in inputs:
        if port.is_clock:
            lines.append(f"# clock {port.name} 0")
        else:
            lines.append(f"# input {port.name} {port.width}")
    for port in outputs:
        lines.append(f"# output {port.name} {port.width}")

    non_clock_inputs = [p for p in inputs if not p.is_clock]
    bits = ""
    for port in non_clock_inputs:
        value = drive.get(port.name, 0)
        bits += format(value, f"0{port.width}b")
    out_bits = "-" if not outputs else "0" * sum(p.width for p in outputs)
    for cycle in range(cycles):
        lines.append(f"{cycle} {bits} {out_bits}")
    return "\n".join(lines) + "\n"


def build_iverilog_testbench(
    module_name: str, inputs: list[Port], drive: dict[str, int], victim: str, cycles: int = 4
) -> str:
    """A minimal self-checking testbench: drives every `drive` input to a fixed value, holds it
    for `cycles` clock edges (if a clock port is present) or `cycles` time units otherwise, then
    `$display`s `victim` and `$finish`es. `module_name` must match the design's top module."""
    clock = next((p for p in inputs if p.is_clock), None)
    decls = "\n".join(f"    reg [{p.width - 1}:0] {p.name};" for p in inputs)
    drives = "\n".join(
        f"        {name} = {value};" for name, value in drive.items()
    )
    ports = ", ".join(f".{p.name}({p.name})" for p in inputs)
    if clock is not None:
        clock_gen = f"    always #5 {clock.name} = ~{clock.name};\n"
        wait = f"        repeat ({cycles}) @(posedge {clock.name});\n"
    else:
        clock_gen = ""
        wait = f"        #{cycles * 10};\n"
    return f"""\
// Generated by lemanruss.htl.testbench.build_iverilog_testbench
`timescale 1ns/1ps
module htl_tb;
{decls}
    wire {victim}_out;

    {module_name} dut({ports}, .{victim}({victim}_out));

{clock_gen}
    initial begin
{drives}
{wait}
        $display("HTL_RESULT %b", {victim}_out);
        $finish;
    end
endmodule
"""
